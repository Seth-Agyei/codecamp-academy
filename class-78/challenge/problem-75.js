function convertToFahrenheit(celsius) {
    const fahrenheit = (celsius * 9/5) + 32
    return fahrenheit
}

// Test the function 
let celsius = 5 
console.log(`${celsius} celsius to Fahrenheit is ${convertToFahrenheit(5)}F`);



